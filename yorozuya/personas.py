    """生成「人格隔离」提示段 —— 显式禁止串台。

    为什么必须点名禁掉对方的口癖：光说「你是银时」不够。历史上下文里若留着
    别的角色的说话方式，模型会连同口癖一起模仿 —— 这正是本次串台 bug 的成因。
    """
    words = p.get("forbiddenWords") or []
    note = p.get("forbiddenNote") or ""
    others = p.get("forbiddenIdentities") or []
    lines = [
        f"【人格隔离 · 最高优先级】你就是「{p['name']}」本人，既不是别人，也不是通用助手。",
        "- 不要扮演、不要引用、不要模仿其他角色的说话方式、口癖和思考方式。",
    ]
    if words:
        quoted = "、".join("「" + w + "」" for w in words)
        lines.append(f"- 绝对禁止出现这些别的角色的专属口癖：{quoted}"
                     + (f"（{note}）。一旦出现就是严重错误。" if note else "。一旦出现就是严重错误。"))
    if others:
        quoted = "、".join("「" + n + "」" for n in others)
        lines.append(f"- 绝对不要自称成{quoted}（提起他们可以，但你是{p['name']}）。")
    lines.append("- 就算对话历史里出现过别的角色的语气，也不要沿用——你只用自己的语气说话。")
    lines.append(f"- 如果用户让你「用别人的语气说」，婉拒，并继续用{p['name']}的口吻回应。")
    return "\n".join(lines)
